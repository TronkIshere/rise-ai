CREATE TABLE settlement_requests (
    id CHAR(36) NOT NULL,
    settlement_code VARCHAR(30) NOT NULL,
    campaign_id CHAR(36) NOT NULL,
    currency CHAR(3) NOT NULL,
    settlement_type VARCHAR(30) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    settlement_status VARCHAR(20) NOT NULL,
    reason VARCHAR(2000) NOT NULL,
    proposed_by CHAR(36) NOT NULL,
    decided_by CHAR(36) NULL,
    decided_at DATETIME(6) NULL,
    decision_reason VARCHAR(2000) NULL,
    executed_at DATETIME(6) NULL,
    donation_count INT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_settlements_code UNIQUE (settlement_code),
    CONSTRAINT fk_settlements_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT fk_settlements_proposer FOREIGN KEY (proposed_by) REFERENCES users (id),
    CONSTRAINT fk_settlements_decider FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT ck_settlements_amount CHECK (amount > 0),
    CONSTRAINT ck_settlements_dual_control CHECK (decided_by IS NULL OR decided_by <> proposed_by),
    INDEX idx_settlements_campaign_status (campaign_id, settlement_status),
    INDEX idx_settlements_status (settlement_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE escrow_adjustments (
    id CHAR(36) NOT NULL,
    adjustment_code VARCHAR(30) NOT NULL,
    campaign_id CHAR(36) NOT NULL,
    currency CHAR(3) NOT NULL,
    direction VARCHAR(10) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    adjustment_status VARCHAR(20) NOT NULL,
    reason VARCHAR(2000) NOT NULL,
    requested_by CHAR(36) NOT NULL,
    decided_by CHAR(36) NULL,
    decided_at DATETIME(6) NULL,
    decision_reason VARCHAR(2000) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_adjustments_code UNIQUE (adjustment_code),
    CONSTRAINT fk_adjustments_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT fk_adjustments_requester FOREIGN KEY (requested_by) REFERENCES users (id),
    CONSTRAINT fk_adjustments_decider FOREIGN KEY (decided_by) REFERENCES users (id),
    CONSTRAINT ck_adjustments_amount CHECK (amount > 0),
    CONSTRAINT ck_adjustments_direction CHECK (direction IN ('CREDIT', 'DEBIT')),
    CONSTRAINT ck_adjustments_dual_control CHECK (decided_by IS NULL OR decided_by <> requested_by),
    INDEX idx_adjustments_campaign_status (campaign_id, adjustment_status),
    INDEX idx_adjustments_status (adjustment_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
