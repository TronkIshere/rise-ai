CREATE TABLE campaign_milestones (
    id CHAR(36) NOT NULL,
    campaign_id CHAR(36) NOT NULL,
    title VARCHAR(200) NOT NULL,
    description TEXT NULL,
    sequence_number INT NOT NULL,
    planned_amount DECIMAL(19,2) NOT NULL,
    reserved_amount DECIMAL(19,2) NOT NULL DEFAULT 0,
    released_amount DECIMAL(19,2) NOT NULL DEFAULT 0,
    start_at DATETIME(6) NOT NULL,
    due_at DATETIME(6) NOT NULL,
    release_conditions TEXT NOT NULL,
    expected_deliverables TEXT NOT NULL,
    milestone_status VARCHAR(30) NOT NULL,
    pre_dispute_status VARCHAR(30) NULL,
    submitted_at DATETIME(6) NULL,
    reviewed_at DATETIME(6) NULL,
    completed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_milestones_sequence UNIQUE (campaign_id, sequence_number),
    CONSTRAINT fk_milestones_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT ck_milestones_amounts CHECK (planned_amount > 0 AND reserved_amount >= 0 AND released_amount >= 0 AND reserved_amount + released_amount <= planned_amount),
    CONSTRAINT ck_milestones_sequence CHECK (sequence_number > 0),
    CONSTRAINT ck_milestones_dates CHECK (due_at > start_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE donations (
    id CHAR(36) NOT NULL,
    donation_code VARCHAR(30) NOT NULL,
    campaign_id CHAR(36) NOT NULL,
    donor_id CHAR(36) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    refunded_amount DECIMAL(19,2) NOT NULL DEFAULT 0,
    currency CHAR(3) NOT NULL,
    donation_status VARCHAR(30) NOT NULL,
    payment_method VARCHAR(40) NOT NULL,
    is_anonymous BOOLEAN NOT NULL DEFAULT FALSE,
    donor_message VARCHAR(1000) NULL,
    simulated_reference VARCHAR(100) NULL,
    idempotency_key VARCHAR(100) NULL,
    confirmed_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_donations_code UNIQUE (donation_code),
    CONSTRAINT uk_donations_idempotency UNIQUE (donor_id, idempotency_key),
    CONSTRAINT fk_donations_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT fk_donations_donor FOREIGN KEY (donor_id) REFERENCES users (id),
    CONSTRAINT ck_donations_amounts CHECK (amount > 0 AND refunded_amount >= 0 AND refunded_amount <= amount),
    INDEX idx_donations_campaign_status (campaign_id, donation_status),
    INDEX idx_donations_donor (donor_id, created_at),
    INDEX idx_donations_status (donation_status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE escrow_accounts (
    id CHAR(36) NOT NULL,
    campaign_id CHAR(36) NOT NULL,
    currency CHAR(3) NOT NULL,
    total_confirmed_contributions DECIMAL(19,2) NOT NULL DEFAULT 0,
    total_reserved DECIMAL(19,2) NOT NULL DEFAULT 0,
    total_disbursed DECIMAL(19,2) NOT NULL DEFAULT 0,
    total_refunded DECIMAL(19,2) NOT NULL DEFAULT 0,
    available_balance DECIMAL(19,2) NOT NULL DEFAULT 0,
    escrow_status VARCHAR(20) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_escrow_accounts_campaign_currency UNIQUE (campaign_id, currency),
    CONSTRAINT fk_escrow_accounts_campaign FOREIGN KEY (campaign_id) REFERENCES campaigns (id),
    CONSTRAINT ck_escrow_non_negative CHECK (total_confirmed_contributions >= 0 AND total_reserved >= 0 AND total_disbursed >= 0 AND total_refunded >= 0 AND available_balance >= 0),
    CONSTRAINT ck_escrow_balance_identity CHECK (available_balance = total_confirmed_contributions - total_reserved - total_disbursed - total_refunded)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

