    CONSTRAINT ck_campaigns_dates CHECK (end_at > start_at),
    INDEX idx_campaigns_status (campaign_status, created_at),
    INDEX idx_campaigns_creator (creator_id),
    INDEX idx_campaigns_organization (organization_id),
