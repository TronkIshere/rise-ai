CREATE TABLE campaigns (
    id CHAR(36) NOT NULL,
    campaign_code VARCHAR(30) NOT NULL,
    creator_id CHAR(36) NOT NULL,
    organization_id CHAR(36) NOT NULL,
    title VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL,
    short_description VARCHAR(500) NOT NULL,
    full_description MEDIUMTEXT NOT NULL,
    cover_image_url VARCHAR(500) NULL,
    gallery_image_urls JSON NULL,
    category VARCHAR(40) NOT NULL,
    beneficiary_description VARCHAR(2000) NOT NULL,
    target_amount DECIMAL(19,2) NOT NULL,
    currency CHAR(3) NOT NULL,
    minimum_donation_amount DECIMAL(19,2) NOT NULL,
    start_at DATETIME(6) NOT NULL,
    end_at DATETIME(6) NOT NULL,
    location VARCHAR(255) NOT NULL,
    beneficiary_count INT NOT NULL,
    problem_statement TEXT NOT NULL,
    solution_description TEXT NOT NULL,
    impact_goals TEXT NOT NULL,
    budget_breakdown JSON NULL,
    campaign_status VARCHAR(30) NOT NULL,
    review_status VARCHAR(30) NOT NULL,
    review_note VARCHAR(2000) NULL,
    published_at DATETIME(6) NULL,
    completed_at DATETIME(6) NULL,
    cancelled_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_campaigns_code UNIQUE (campaign_code),
    CONSTRAINT uk_campaigns_slug UNIQUE (slug),
