CREATE TABLE outbox_events (
    id CHAR(36) NOT NULL,
    event_id CHAR(36) NOT NULL,
    event_type VARCHAR(80) NOT NULL,
    schema_version INT NOT NULL,
    aggregate_type VARCHAR(40) NOT NULL,
    aggregate_id CHAR(36) NOT NULL,
    actor_id CHAR(36) NULL,
    correlation_id VARCHAR(64) NULL,
    envelope MEDIUMTEXT NOT NULL,
    occurred_at DATETIME(6) NOT NULL,
    status VARCHAR(20) NOT NULL,
    attempts INT NOT NULL DEFAULT 0,
    next_attempt_at DATETIME(6) NOT NULL,
    lease_until DATETIME(6) NULL,
    last_error VARCHAR(500) NULL,
    published_at DATETIME(6) NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (id),
    CONSTRAINT uk_outbox_events_event_id UNIQUE (event_id),
    CONSTRAINT ck_outbox_events_status CHECK (status IN ('PENDING', 'IN_FLIGHT', 'PUBLISHED', 'FAILED')),
    CONSTRAINT ck_outbox_events_attempts CHECK (attempts >= 0),
    INDEX idx_outbox_events_due (status, next_attempt_at),
    INDEX idx_outbox_events_aggregate (aggregate_type, aggregate_id, occurred_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
